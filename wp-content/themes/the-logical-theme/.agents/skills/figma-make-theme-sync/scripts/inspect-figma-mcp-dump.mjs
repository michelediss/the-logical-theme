import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const themeRoot = path.resolve(__dirname, '../../../../');
const defaultDumpRoot = path.join(themeRoot, '.artifacts', 'figma-mcp-debug');

function parseArgs(argv) {
  const args = {};

  for (let index = 2; index < argv.length; index += 1) {
    const token = argv[index];

    if (!token.startsWith('--')) {
      continue;
    }

    const key = token.slice(2);
    const next = argv[index + 1];

    if (!next || next.startsWith('--')) {
      args[key] = true;
      continue;
    }

    args[key] = next;
    index += 1;
  }

  return args;
}

const args = parseArgs(process.argv);
const dumpId = args['dump-id'] ?? 'ugHr0Gh5yVbWe2mtIPCLIG';
const dumpDir = path.join(defaultDumpRoot, dumpId);
const manifestPath = path.join(dumpDir, 'manifest.json');

if (!fs.existsSync(manifestPath)) {
  console.error(`Missing manifest: ${manifestPath}`);
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const sourceFiles = manifest.savedSources ?? [];
const imageFiles = manifest.savedImages ?? [];

console.log(`Dump: ${dumpId}`);
console.log(`App URL: ${manifest.appUrl}`);
console.log(`Generated by: ${manifest.generatedBy}`);
console.log(`Source files: ${sourceFiles.length}`);
for (const file of sourceFiles) {
  console.log(`  - ${file}`);
}

console.log(`Image files: ${imageFiles.length}`);
for (const file of imageFiles) {
  console.log(`  - ${file}`);
}

if (Array.isArray(manifest.notes) && manifest.notes.length > 0) {
  console.log('Notes:');
  for (const note of manifest.notes) {
    console.log(`  - ${note}`);
  }
}
